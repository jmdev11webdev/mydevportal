export const techStackGroups = [
    'Languages',
    'Frontend',
    'Backend',
    'Database',
    'DevOps & Cloud',
    'Tooling & Testing',
] as const;

export function resolveTechOption(name: string): TechOption | null {
    const normalized = name.trim().toLowerCase();
    if (!normalized) {
        return null;
    }

    return (
        techStackCatalog.find(
            (item) =>
                item.label.toLowerCase() === normalized ||
                item.aliases?.some(
                    (alias) => alias.toLowerCase() === normalized,
                ),
        ) ?? null
    );
}

export function getTechIconClass(name: string): string | null {
    return resolveTechOption(name)?.iconClass ?? null;
}

export function getTechBrandColor(name: string): string {
    return resolveTechOption(name)?.brandColor ?? '#64748B';
}

export function getTechBadgeStyle(name: string): Record<string, string> {
    const color = getTechBrandColor(name);

    return {
        backgroundColor: `color-mix(in oklab, ${color} 15%, transparent)`,
        borderColor: `color-mix(in oklab, ${color} 38%, transparent)`,
    };
}

export function getTechMarkdownBadge(name: string): string {
    const option = resolveTechOption(name);
    const label = option?.label ?? name.trim();
    const hex = (option?.brandColor ?? '#475569').replace('#', '');
    const textColor = option?.badgeTextColor ?? 'white';
    const encodedLabel = encodeURIComponent(label.replace(/-/g, '--'));
    const logoPart = option?.badgeLogo
        ? `&logo=${encodeURIComponent(option.badgeLogo)}&logoColor=${textColor}`
        : '';

    return `![${label}](https://img.shields.io/badge/${encodedLabel}-${hex}?style=for-the-badge${logoPart})`;
}

export function suggestStackCategory(name: string): StackCategory {
    return resolveTechOption(name)?.category ?? 'tooling';
}
